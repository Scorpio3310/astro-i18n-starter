/**
 * robots.txt endpoint for Astro
 *
 * Generated once at build time (static file endpoint), so the decision is made
 * from the build environment, not per request:
 * - `site` is a real domain (PRODUCTION_DOMAIN was set): allows crawlers and links the sitemap
 * - `site` is the localhost fallback (PRODUCTION_DOMAIN not set): blocks all crawlers (disallow all)
 *
 * `site` is the single source of truth: astro.config.mjs resolves it from
 * PRODUCTION_DOMAIN (build environment first, then .env), so robots.txt always
 * matches the canonical URLs and the sitemap.
 *
 * Usage: Accessible at /robots.txt
 */

import type { APIRoute } from "astro";
import DEV_ROBOTS_TXT from "@data/robots/dev_robots.txt?raw";
import PRODUCTION_ROBOTS_TXT from "@data/robots/production_robots.txt?raw";

export const prerender = true;

export const GET: APIRoute = ({ site }) => {
    // Without PRODUCTION_DOMAIN the config falls back to http://localhost:4321
    const isProd = !!site && site.hostname !== "localhost";

    // Production robots links the sitemap generated by @astrojs/sitemap
    const robotsContent = isProd
        ? PRODUCTION_ROBOTS_TXT.replace(
              "{{SITEMAP_URL}}",
              new URL("sitemap-index.xml", site).href
          )
        : DEV_ROBOTS_TXT;

    // Return robots.txt with proper content-type header
    return new Response(robotsContent, {
        headers: {
            "Content-Type": "text/plain",
        },
    });
};
